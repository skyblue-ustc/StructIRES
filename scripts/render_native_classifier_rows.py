#!/usr/bin/env python3
"""Render the StructIRES native-classifier LaTex rows from a verified aggregate."""
from __future__ import annotations

import argparse
import csv
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INPUT = Path("/9950backfile/lant/data/ires-design-external-runs/") / \
    "structires_native_authorstyle_batchshuffle_multifold_0_2_4_v2_20260823/aggregate_metrics.csv"
DEFAULT_OUTPUT = ROOT / "paper" / "bibe2026" / "tables" / "recognition_native_rows.tex"


def arguments() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--protocol-label", default=None,
                        help="Optional complete LaTex protocol cell; defaults to '<n>-fold validation-clean native folds'.")
    return parser.parse_args()


def value(row: dict[str, str], key: str) -> float:
    try:
        return float(row[key])
    except (KeyError, ValueError) as exc:
        raise ValueError(f"missing numeric {key}") from exc


def metric(row: dict[str, str], name: str) -> str:
    return f"${value(row, name + '_mean'):.3f}\\pm{value(row, name + '_std'):.3f}$"


def plain_metric(row: dict[str, str], name: str) -> str:
    """A math-mode-ready metric for prose macros (without surrounding dollars)."""
    return f"{value(row, name + '_mean'):.3f}\\pm{value(row, name + '_std'):.3f}"


def signed(value_: float) -> str:
    return f"{value_:+.3f}"


def main() -> int:
    args = arguments()
    with args.input.open(encoding="utf-8", newline="") as handle:
        rows = {row["model"]: row for row in csv.DictReader(handle)}
    expected = {"author_style_sequence_only", "structires_mfe_contact_fusion"}
    if set(rows) != expected:
        raise ValueError(f"unexpected model rows: {sorted(rows)}")
    n_folds = int(value(rows["author_style_sequence_only"], "n_folds"))
    if int(value(rows["structires_mfe_contact_fusion"], "n_folds")) != n_folds:
        raise ValueError("unmatched fold counts")
    protocol = args.protocol_label or f"{n_folds}-fold validation-clean native folds"
    sequence = rows["author_style_sequence_only"]
    contact = rows["structires_mfe_contact_fusion"]
    rendered = [
        "%% Generated by scripts/render_native_classifier_rows.py from independently verified aggregate_metrics.csv.",
        "%% Do not hand-edit numerical values; rerun after updating the immutable multifold summary.",
        f"\\newcommand{{\\StructIRESNativeFoldCount}}{{{n_folds}}}",
        f"\\newcommand{{\\StructIRESNativeSeqAUC}}{{{plain_metric(sequence, 'auc')}}}",
        f"\\newcommand{{\\StructIRESNativeSeqAUPR}}{{{plain_metric(sequence, 'aupr')}}}",
        f"\\newcommand{{\\StructIRESNativeSeqFOne}}{{{plain_metric(sequence, 'f1')}}}",
        f"\\newcommand{{\\StructIRESNativeSeqMCC}}{{{plain_metric(sequence, 'mcc')}}}",
        f"\\newcommand{{\\StructIRESNativeSeqECE}}{{{plain_metric(sequence, 'ece10')}}}",
        f"\\newcommand{{\\StructIRESNativeContactAUC}}{{{plain_metric(contact, 'auc')}}}",
        f"\\newcommand{{\\StructIRESNativeContactAUPR}}{{{plain_metric(contact, 'aupr')}}}",
        f"\\newcommand{{\\StructIRESNativeContactFOne}}{{{plain_metric(contact, 'f1')}}}",
        f"\\newcommand{{\\StructIRESNativeContactMCC}}{{{plain_metric(contact, 'mcc')}}}",
        f"\\newcommand{{\\StructIRESNativeContactECE}}{{{plain_metric(contact, 'ece10')}}}",
        f"\\newcommand{{\\StructIRESNativeDeltaAUC}}{{{signed(value(contact, 'auc_mean') - value(sequence, 'auc_mean'))}}}",
        f"\\newcommand{{\\StructIRESNativeDeltaAUPR}}{{{signed(value(contact, 'aupr_mean') - value(sequence, 'aupr_mean'))}}}",
        f"\\newcommand{{\\StructIRESNativeDeltaFOne}}{{{signed(value(contact, 'f1_mean') - value(sequence, 'f1_mean'))}}}",
        f"\\newcommand{{\\StructIRESNativeDeltaMCC}}{{{signed(value(contact, 'mcc_mean') - value(sequence, 'mcc_mean'))}}}",
        f"\\newcommand{{\\StructIRESNativeDeltaECE}}{{{signed(value(contact, 'ece10_mean') - value(sequence, 'ece10_mean'))}}}",
        "\\newcommand{\\StructIRESNativeRows}{%",
        "RNA-FM sequence-only re-train & public RNA-FM & Matched local re-train & "
        f"{protocol} & {metric(rows['author_style_sequence_only'], 'auc')} & "
        f"{metric(rows['author_style_sequence_only'], 'aupr')} & {metric(rows['author_style_sequence_only'], 'f1')} \\\\",
        "\\textsc{StructIRES-Classifier} & RNA-FM + MFE contacts & Matched local re-train & "
        f"{protocol} & {metric(rows['structires_mfe_contact_fusion'], 'auc')} & "
        f"{metric(rows['structires_mfe_contact_fusion'], 'aupr')} & {metric(rows['structires_mfe_contact_fusion'], 'f1')} \\\\",
        "}",
    ]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(rendered) + "\n", encoding="utf-8")
    print(args.output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
